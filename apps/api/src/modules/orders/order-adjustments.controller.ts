import {
  Body,
  Controller,
  Headers,
  HttpCode,
  Param,
  ParseIntPipe,
  Post,
  Req,
} from '@nestjs/common';
import {
  ApiCookieAuth,
  ApiCreatedResponse,
  ApiHeader,
  ApiOperation,
  ApiParam,
  ApiTags,
} from '@nestjs/swagger';
import { UserRequest } from 'src/common/interfaces/user-request.interface';
import {
  ACCESS_TOKEN_SECURITY_SCHEME,
  ApiAuthRequired,
  ApiConflict,
  ApiInvalidInput,
  ApiNotFound,
  ApiRoleForbidden,
  PARSE_INT_PIPE_400,
  VALIDATION_PIPE_400,
  successEnvelopeSchema,
} from 'src/configs/swagger.config';
import { Audiences } from 'src/modules/auth/decorators/audience.decorator';
import { Roles } from 'src/modules/auth/decorators/role.decorator';
import { auditActorFrom } from 'src/modules/audit/audit-actor';
import UserRoleEnum from '../user/enums/user-role.enum';
import { CreateLineAdjustmentDto } from './dto/create-line-adjustment.dto';
import {
  IDEMPOTENCY_KEY_MAX_LENGTH,
  IDEMPOTENCY_KEY_MIN_LENGTH,
  POS_IDEMPOTENCY_HEADER,
  requireIdempotencyKey,
} from './idempotency.helper';
import {
  LineAdjustmentMessages,
  OrderAdjustmentsService,
} from './order-adjustments.service';

/**
 * ============================================================================
 * PARTIAL RETURNS AND REFUNDS OF A SALE — super_admin only, by ROLE.
 * ============================================================================
 *
 *   POST /admin/orders/:orderId/line-adjustments
 *
 * WHY THERE IS NO `@RequirePermissions`. Every figure this route writes and
 * answers with — revenue reversed and, above all, the exact COGS given back to
 * the pool — is cost data, and cost is the main administrator's alone
 * (docs/PURCHASE-COST-ACCOUNTING.md §8, owner decision B-2), exactly like
 * `/reports/*`. A catalogue capability exists so that it CAN be delegated, so
 * publishing one here would make the rule a convention. The route is therefore
 * one of the deliberate role-only admin routes, and
 * `OrderAdjustmentsService.assertSuperAdmin` repeats the check below the
 * guard.
 *
 * A SEPARATE CONTROLLER rather than another handler on `OrdersController`,
 * whose every management route is capability-gated: keeping the role-only
 * route on its own class means the class-level `@Roles` cannot be forgotten on
 * a handler added later.
 */
@ApiCookieAuth(ACCESS_TOKEN_SECURITY_SCHEME)
@ApiTags('Orders Management')
@Roles(UserRoleEnum.superAdmin)
@Audiences('admin')
@Controller('admin/orders')
export class OrderAdjustmentsController {
  constructor(private readonly adjustments: OrderAdjustmentsService) {}

  @ApiOperation({
    summary: 'Record a partial return and/or refund of order lines',
    description:
      '`kind`: `return_refund` (goods and money back), `refund_only` (money ' +
      'back, goods kept — no stock or cost moves), `return_only` (goods back, ' +
      'no money). Returned units go back to stock with the LINE`S OWN ' +
      'recognised cost (unknown-cost units first), never the current average.\n\n' +
      'The order must be a completed sale (paid / processing / shipped / ' +
      'delivered, not voided). The order status, `voidedAt`, `refundedAt` and ' +
      'the payment rows are NEVER changed: a refund here records money the ' +
      'operator already returned outside the system. Once an order has a line ' +
      'adjustment, whole-order void / return / external refund are refused ' +
      '(`ORDER_HAS_LINE_ADJUSTMENTS`); finish the order here.\n\n' +
      '**`Idempotency-Key` is required.** Same key + same body replays the ' +
      'stored 201; same key + different body is `409` with ' +
      '`error: "IDEMPOTENCY_KEY_REUSED"`.\n\n' +
      'Money in the response is integer Rial as a base-10 STRING.',
  })
  @ApiParam({ name: 'orderId', type: Number, example: 41 })
  @ApiHeader({
    name: POS_IDEMPOTENCY_HEADER,
    required: true,
    description:
      `Client-generated key for this adjustment attempt (scope ` +
      `\`order_line_adjustment\`). ${IDEMPOTENCY_KEY_MIN_LENGTH}-` +
      `${IDEMPOTENCY_KEY_MAX_LENGTH} characters from [A-Za-z0-9._:-]. ` +
      'Generated by the admin client, never typed by a person.',
    example: '6a1f0c7e-2b4d-4f7a-9d3e-0b8c5e2f1a47',
  })
  @ApiCreatedResponse({
    description:
      'Adjustment recorded (or an identical earlier attempt replayed). ' +
      '`{ orderId, kind, adjustments: [{ id, orderItemId, revenueQuantity, ' +
      'revenueReversed, restockedKnownQuantity, restockedUnknownQuantity, ' +
      'cogsReversed }], totals: { revenueReversed, cogsReversed, ' +
      'unitsRestocked } }`.',
    schema: successEnvelopeSchema({
      message: LineAdjustmentMessages.CREATED,
      data: { type: 'object' },
    }),
  })
  @ApiInvalidInput(
    `${PARSE_INT_PIPE_400}. ${VALIDATION_PIPE_400}. Also: a missing or ` +
      'malformed `Idempotency-Key` (`IDEMPOTENCY_KEY_REQUIRED` / ' +
      '`IDEMPOTENCY_KEY_INVALID`), and a line that is not part of this order ' +
      '(`details.field` names it, e.g. `lines[0].orderItemId`).',
  )
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No order has that id.')
  @ApiConflict(
    '`ORDER_NOT_ADJUSTABLE` (voided, refunded, canceled, failed or never ' +
      'paid), `ORDER_LINE_NOT_FULFILLED` (the line never left the shelf — ' +
      'cancel the order instead), `ADJUSTMENT_EXCEEDS_LINE` (more units than ' +
      'remain; `details.remaining` has `revenueUnits` and `restockUnits`), ' +
      '`IDEMPOTENCY_KEY_REUSED`, `IDEMPOTENCY_REQUEST_IN_PROGRESS`.',
  )
  @HttpCode(201)
  @Post(':orderId/line-adjustments')
  async create(
    @Param('orderId', ParseIntPipe) orderId: number,
    @Body() dto: CreateLineAdjustmentDto,
    @Req() req: UserRequest,
    @Headers('idempotency-key') idempotencyKeyHeader?: string,
  ) {
    // Validated before anything touches the database, so a request that
    // cannot be made safe provably writes nothing.
    const idempotencyKey = requireIdempotencyKey(idempotencyKeyHeader, {
      missing: LineAdjustmentMessages.IDEMPOTENCY_KEY_REQUIRED,
      invalid: LineAdjustmentMessages.IDEMPOTENCY_KEY_INVALID,
    });
    const data = await this.adjustments.create(orderId, dto, idempotencyKey, {
      userId: req.user.sub,
      roles: req.user.roles,
      audit: auditActorFrom(req),
    });
    return { message: LineAdjustmentMessages.CREATED, data };
  }
}
