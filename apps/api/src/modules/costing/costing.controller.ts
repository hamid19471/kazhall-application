import {
  Body,
  Controller,
  Get,
  Headers,
  HttpCode,
  Param,
  ParseIntPipe,
  Post,
  Put,
  Query,
  Req,
} from '@nestjs/common';
import {
  ApiCookieAuth,
  ApiCreatedResponse,
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
} from '@nestjs/swagger';

import { UserRequest } from 'src/common/interfaces/user-request.interface';
import {
  ACCESS_TOKEN_SECURITY_SCHEME,
  ApiAuthRequired,
  ApiConflict,
  ApiInvalidInput,
  ApiNotFound,
  ApiRoleForbidden,
  PARSE_INT_PIPE_400,
  VALIDATION_PIPE_400,
  successEnvelopeSchema,
} from 'src/configs/swagger.config';
import { auditActorFrom } from 'src/modules/audit/audit-actor';
import { Audiences } from 'src/modules/auth/decorators/audience.decorator';
import { Roles } from 'src/modules/auth/decorators/role.decorator';
import {
  POS_IDEMPOTENCY_HEADER,
  requireIdempotencyKey,
} from 'src/modules/orders/idempotency.helper';
import UserRoleEnum from 'src/modules/user/enums/user-role.enum';

import { CostingConsoleMessages } from './costing.messages';
import { CostingPrincipal, CostingService } from './costing.service';
import {
  InitialiseValuationDto,
  RecordCorrectionDto,
  RecordReceiptDto,
  SetPurchasePriceDto,
  UnvaluedQueryDto,
} from './dto/costing.dto';

const MONEY_CONTRACT =
  'Every Rial figure in a response is an integer-Rial BASE-10 STRING ("125000"), never a JSON ' +
  'number: inventory values are bigint totals over up to MAX_STOCK_UNITS units. Counts stay numbers.';

const IDEMPOTENCY =
  'Requires an `Idempotency-Key` header (8..200 chars of [A-Za-z0-9._:-]) generated by the ' +
  'client once per submission. The same key with the same body replays the stored response ' +
  '(nothing is applied twice); the same key with a different body is 409.';

const VARIANT_PARAM = {
  name: 'variantId',
  type: Number,
  description: 'Numeric `product_variants.id` — cost belongs to the VARIANT.',
  example: 7,
};

/**
 * ============================================================================
 * /admin/costing — purchase cost and inventory valuation.
 * ============================================================================
 *
 * Contract: docs/PURCHASE-COST-ACCOUNTING.md §6, §8, §13.
 *
 * AUTHORIZATION: THE BUILT-IN `super_admin` ROLE, ON AN `admin` SESSION —
 * the same rule, and the same two class-level gates, as `/reports`:
 *
 *   `@Audiences('admin')`   a till or storefront session is not admitted at
 *                           all, whoever holds it;
 *   `@Roles(superAdmin)`    the principal must hold the built-in role.
 *
 * THERE IS DELIBERATELY NO `@RequirePermissions`. A catalogue permission exists
 * so that it CAN be delegated, and purchase cost is not delegable (owner
 * decision B-2): a delegated administrator holding every grantable capability
 * is refused here with 403. `CostingService` re-asserts the role on every
 * method, so removing a decorator does not open a route.
 *
 * The idempotency key is read here and validated with the shared rules
 * (`requireIdempotencyKey`), so a missing or malformed key is a 400 before any
 * transaction opens.
 */
@ApiCookieAuth(ACCESS_TOKEN_SECURITY_SCHEME)
@ApiTags('Inventory costing')
@Roles(UserRoleEnum.superAdmin)
@Controller('admin/costing')
@Audiences('admin')
export class CostingController {
  constructor(private readonly costing: CostingService) {}

  @ApiOperation({
    summary: "One variant's valuation pool and its recent costed ledger",
    description:
      'The pool (`stock`, `unvaluedQuantity`, `valuedQuantity`, `inventoryCostValue`, ' +
      'display-only `averageUnitCost`, `costStatus`), the remembered `lastPurchaseUnitCost`, ' +
      'and the latest 20 movements newest first with their cost evidence. ' +
      MONEY_CONTRACT,
  })
  @ApiParam(VARIANT_PARAM)
  @ApiOkResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(PARSE_INT_PIPE_400)
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No variant has that id.')
  @Get('variants/:variantId')
  async variant(
    @Req() req: UserRequest,
    @Param('variantId', ParseIntPipe) variantId: number,
  ) {
    return {
      data: await this.costing.getVariant(variantId, principalOf(req)),
    };
  }

  @ApiOperation({
    summary: 'Every variant of a product with its valuation, plus totals',
    description: MONEY_CONTRACT,
  })
  @ApiParam({ name: 'productId', type: Number, example: 12 })
  @ApiOkResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(PARSE_INT_PIPE_400)
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No product has that id.')
  @Get('products/:productId')
  async product(
    @Req() req: UserRequest,
    @Param('productId', ParseIntPipe) productId: number,
  ) {
    return {
      data: await this.costing.getProduct(productId, principalOf(req)),
    };
  }

  @ApiOperation({
    summary: 'The legacy-valuation work list',
    description:
      'Paginated variants that still hold UNVALUED units (`unvaluedQuantity > 0`), ascending ' +
      'variant id. ' +
      MONEY_CONTRACT,
  })
  @ApiOkResponse({
    schema: successEnvelopeSchema({
      data: { type: 'array', items: { type: 'object' } },
      properties: {
        total: { type: 'integer' },
        page: { type: 'integer' },
        limit: { type: 'integer' },
        totalPages: { type: 'integer' },
      },
    }),
  })
  @ApiInvalidInput(VALIDATION_PIPE_400)
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @Get('unvalued')
  async unvalued(@Req() req: UserRequest, @Query() query: UnvaluedQueryDto) {
    return this.costing.listUnvalued(query, principalOf(req));
  }

  @ApiOperation({
    summary: 'Record a purchase receipt (units in at a known unit cost)',
    description:
      'Stock += quantity; inventory value += quantity × unitCost, exactly. Writes one ' +
      '`stock_receipt` movement with its cost evidence and remembers `unitCost` as the ' +
      'next default. ' +
      IDEMPOTENCY +
      ' The 409 is `error: STOCK_RECEIPT_IDEMPOTENCY_CONFLICT`. ' +
      MONEY_CONTRACT,
  })
  @ApiParam(VARIANT_PARAM)
  @ApiHeader({ name: POS_IDEMPOTENCY_HEADER, required: true })
  @ApiCreatedResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(
    `${PARSE_INT_PIPE_400}. ${VALIDATION_PIPE_400}. Money input errors carry ` +
      '`error` PURCHASE_COST_REQUIRED / PURCHASE_COST_INVALID / PURCHASE_COST_OUT_OF_RANGE.',
  )
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No variant has that id.')
  @ApiConflict('Same Idempotency-Key, different body.')
  @Post('variants/:variantId/receipts')
  async receipt(
    @Req() req: UserRequest,
    @Param('variantId', ParseIntPipe) variantId: number,
    @Headers('idempotency-key') rawKey: string | undefined,
    @Body() dto: RecordReceiptDto,
  ) {
    const key = costingKey(rawKey);
    return {
      data: await this.costing.recordReceipt(
        variantId,
        dto,
        key,
        principalOf(req),
      ),
    };
  }

  @ApiOperation({
    summary: 'Record a stock correction with an explicit cost policy',
    description:
      'Positive `quantityDelta`: exactly one of `unitCost` (valued) or `costUnknown: true` ' +
      '(recorded as unvalued — unknown, never zero). Negative: neither; unknown-cost units ' +
      'leave first and the rest take an exact share of the value, returned as `costRemoved` ' +
      'and reported as an inventory loss, never as sales COGS. Refused below reserved stock ' +
      '(409 STOCK_BELOW_RESERVED) unless `allowBelowReserved`. ' +
      IDEMPOTENCY +
      ' The 409 is `error: IDEMPOTENCY_KEY_REUSED`. ' +
      MONEY_CONTRACT,
  })
  @ApiParam(VARIANT_PARAM)
  @ApiHeader({ name: POS_IDEMPOTENCY_HEADER, required: true })
  @ApiCreatedResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(
    `${PARSE_INT_PIPE_400}. ${VALIDATION_PIPE_400}. A cost-policy violation is ` +
      '`error: PURCHASE_COST_INVALID` with `details.field`. A result below zero is refused.',
  )
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No variant has that id.')
  @ApiConflict(
    'STOCK_BELOW_RESERVED, or IDEMPOTENCY_KEY_REUSED (same key, different body).',
  )
  @Post('variants/:variantId/corrections')
  async correction(
    @Req() req: UserRequest,
    @Param('variantId', ParseIntPipe) variantId: number,
    @Headers('idempotency-key') rawKey: string | undefined,
    @Body() dto: RecordCorrectionDto,
  ) {
    const key = costingKey(rawKey);
    return {
      data: await this.costing.recordCorrection(
        variantId,
        dto,
        key,
        principalOf(req),
      ),
    };
  }

  @ApiOperation({
    summary: "Value a variant's legacy unvalued units for the first time",
    description:
      'Exactly one of `unitCost` (applied to every unvalued unit) or `totalValue` (the value ' +
      'of all of them). `expectedUnvaluedQuantity` must equal the current count, else 409 ' +
      'INVENTORY_VALUATION_STALE; nothing left to value is 409 INVENTORY_ALREADY_VALUED. ' +
      'Writes one `valuation_initialization` movement with delta 0; stock does not change. ' +
      IDEMPOTENCY +
      ' The 409 is `error: IDEMPOTENCY_KEY_REUSED`. ' +
      MONEY_CONTRACT,
  })
  @ApiParam(VARIANT_PARAM)
  @ApiHeader({ name: POS_IDEMPOTENCY_HEADER, required: true })
  @ApiCreatedResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(`${PARSE_INT_PIPE_400}. ${VALIDATION_PIPE_400}.`)
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No variant has that id.')
  @ApiConflict(
    'INVENTORY_VALUATION_STALE, INVENTORY_ALREADY_VALUED, or IDEMPOTENCY_KEY_REUSED.',
  )
  @Post('variants/:variantId/valuation')
  async valuation(
    @Req() req: UserRequest,
    @Param('variantId', ParseIntPipe) variantId: number,
    @Headers('idempotency-key') rawKey: string | undefined,
    @Body() dto: InitialiseValuationDto,
  ) {
    const key = costingKey(rawKey);
    return {
      data: await this.costing.initialiseValuation(
        variantId,
        dto,
        key,
        principalOf(req),
      ),
    };
  }

  @ApiOperation({
    summary: 'Set or clear the remembered purchase price',
    description:
      'Sets `lastPurchaseUnitCost` only — the default the receipt form pre-fills. Changes no ' +
      'stock and no inventory value. `unitCost: null` clears it. ' +
      MONEY_CONTRACT,
  })
  @ApiParam(VARIANT_PARAM)
  @ApiOkResponse({
    schema: successEnvelopeSchema({ data: { type: 'object' } }),
  })
  @ApiInvalidInput(`${PARSE_INT_PIPE_400}. ${VALIDATION_PIPE_400}.`)
  @ApiAuthRequired()
  @ApiRoleForbidden('super_admin')
  @ApiNotFound('No variant has that id.')
  @HttpCode(200)
  @Put('variants/:variantId/purchase-price')
  async purchasePrice(
    @Req() req: UserRequest,
    @Param('variantId', ParseIntPipe) variantId: number,
    @Body() dto: SetPurchasePriceDto,
  ) {
    return {
      data: await this.costing.setPurchasePrice(
        variantId,
        dto,
        principalOf(req),
      ),
    };
  }
}

/** The principal is always derived from the verified token, never the body. */
function principalOf(req: UserRequest): CostingPrincipal {
  return {
    userId: req.user.sub,
    roles: req.user.roles,
    actor: auditActorFrom(req),
  };
}

function costingKey(raw: string | undefined): string {
  return requireIdempotencyKey(raw, {
    missing: CostingConsoleMessages.IDEMPOTENCY_KEY_REQUIRED,
    invalid: CostingConsoleMessages.IDEMPOTENCY_KEY_INVALID,
  });
}
