/**
 * Stable machine-readable codes for order failures.
 *
 * These are put on the TOP-LEVEL `error` key of the error envelope (see
 * `GlobalExceptionFilter`), which is where clients are told to branch. They are
 * part of the shipped contract: never rename one, never reuse one for a
 * different condition.
 */
export enum OrderErrorCode {
  /** 409. See `OrderMessages.ORDER_FULFILMENT_INCOMPLETE`. */
  ORDER_FULFILMENT_INCOMPLETE = 'ORDER_FULFILMENT_INCOMPLETE',
}

/**
 * Where an operator resolves an order this API refused to advance. Quoted in
 * the `details` of an `ORDER_FULFILMENT_INCOMPLETE` refusal so the client can
 * link straight to it instead of guessing.
 */
export const RECONCILIATION_QUEUE_PATH = '/payment/admin/reconciliation';
